#!/bin/sh
# Run by dpkg as root after STG is installed.
#
# Ubuntu 24.04+ ships kernel.apparmor_restrict_unprivileged_userns=1, which
# blocks unconfined binaries under /opt/ from creating user namespaces.
# Chromium needs user namespaces to spawn its renderer / GPU sub-processes
# (even with --no-sandbox), so without an AppArmor profile granting
# `userns,` the .deb install fails to launch <webview> guests on a fresh
# Ubuntu 24.04+ VM. The AppImage already has a system-shipped allowlist
# entry, which is why launch.sh works while the .deb didn't.
#
# We install a tiny "default_allow + userns" profile keyed to the binary
# path. If apparmor_parser isn't on the system (Debian without AppArmor,
# raspbian, etc.) we silently skip — the absence of a profile is harmless
# on systems that aren't enforcing the restriction.

set -e

PROFILE_PATH="/etc/apparmor.d/stg-sase-traffic-generator"
BINARY_PATH="/opt/STG - SASE Traffic Generator/stg-sase-traffic-generator"

if [ ! -d /etc/apparmor.d ]; then
  exit 0
fi

cat > "$PROFILE_PATH" <<EOF
# Generated by stg-sase-traffic-generator postinst — do not edit.
# Allows Chromium to create unprivileged user namespaces for sub-processes
# on Ubuntu 24.04+, where they are restricted by default.
abi <abi/4.0>,
include <tunables/global>

profile stg-sase-traffic-generator "$BINARY_PATH" flags=(default_allow) {
  userns,

  include if exists <local/stg-sase-traffic-generator>
}
EOF

# Reload the profile if AppArmor tools are present and the kernel module is
# loaded. On systems without AppArmor (or where it is disabled), the file is
# inert and harmless.
if command -v apparmor_parser >/dev/null 2>&1 && [ -d /sys/kernel/security/apparmor ]; then
  apparmor_parser -r "$PROFILE_PATH" >/dev/null 2>&1 || true
fi

exit 0
